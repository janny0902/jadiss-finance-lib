# BPR(Book Price Ratio, 순자산주가비율)은 BPS를 주가로 나눈 값으로, PBR의 역수에 해당하는 재무지표입니다. 주가 대비 순자산 비율을 나타내며, 자산 가치 관점에서 기업을 평가합니다.
# BPR의 구성 요소:
# BPS(Book Value Per Share):
# 주당순자산가치로, 주식 1주당 순자산 가치입니다.
# 주가(Stock Price):
# 현재 시장에서 거래되고 있는 주식의 가격입니다.
# BPR의 특징:
# 자산 가치 비율:
# 주가에 대한 순자산의 비율을 직접적으로 보여줍니다.
# PBR의 역수:
# BPR = 1/PBR 관계로, PBR이 높으면 BPR은 낮아집니다.
# 청산 가치 관점:
# 기업 청산 시 회수 가능한 자산 비율을 나타냅니다.
# 안전 마진:
# 투자 시 자산 가치에 대한 안전 마진을 평가할 수 있습니다.
# BPR 활용:
# 저평가 판단: 높은 BPR은 주가가 순자산 대비 저평가 가능성
# 가치 투자: 자산 가치 기준 투자 판단에 활용
# 안전성 평가: 자산 대비 주가 수준으로 투자 안전성 평가
# 업종 비교: 자산 집약적 업종에서 특히 유용
# 주의사항:
# 장부 가치 한계: 실제 자산 가치와 장부 가치의 차이
# 업종별 특성: 무형자산 비중이 높은 업종에서는 제한적
# 시장 상황: 시장 전체의 밸류에이션 수준 고려 필요

import pandas as pd

def bpr(bps, stock_price):
    """
    BPR(순자산주가비율) 계산
    
    입력 타입:
    bps (pd.Series): 주당순자산가치(BPS) 데이터 시리즈
    stock_price (pd.Series): 주가 데이터 시리즈
    
    출력 타입:
    dict: {'BPR': pd.Series} - 순자산주가비율 값을 포함한 딕셔너리
    """
    bpr_value = bps / stock_price
    
    return {
        'BPR': bpr_value
    }