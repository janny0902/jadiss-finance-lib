# EPR(Earnings Price Ratio, 수익주가비율)은 EPS를 주가로 나눈 값으로, PER의 역수에 해당하는 재무지표입니다. 주가 대비 수익률을 나타내며, 투자 수익률의 관점에서 기업을 평가합니다.
# EPR의 구성 요소:
# EPS(Earnings Per Share):
# 주당순이익으로, 기업이 주식 1주당 창출한 순이익입니다.
# 주가(Stock Price):
# 현재 시장에서 거래되고 있는 주식의 가격입니다.
# EPR의 특징:
# 수익률 관점:
# 주가에 대한 수익률을 직접적으로 보여주는 지표입니다.
# PER의 역수:
# EPR = 1/PER 관계로, PER이 높으면 EPR은 낮아집니다.
# 투자 효율성:
# 투자한 금액 대비 얼마의 수익을 얻을 수 있는지를 나타냅니다.
# 비교 분석:
# 다른 투자 대안과의 수익률 비교가 용이합니다.
# EPR 활용:
# 투자 수익률: EPR × 100 = 투자 수익률(%)
# 채권 수익률 비교: 채권 수익률과 직접 비교 가능
# 저평가 판단: 높은 EPR은 저평가 가능성을 시사
# 포트폴리오 구성: EPR 기준으로 투자 종목 선별
# 주의사항:
# 미래 수익 불확실: 과거 EPS 기준이므로 미래 수익은 불확실
# 성장성 미반영: 기업의 성장 가능성이 충분히 반영되지 않을 수 있음
# 업종별 차이: 업종에 따라 적정 EPR 수준이 다름

import pandas as pd

def epr(eps, stock_price):
    """
    EPR(수익주가비율) 계산
    
    입력 타입:
    eps (pd.Series): 주당순이익(EPS) 데이터 시리즈
    stock_price (pd.Series): 주가 데이터 시리즈
    
    출력 타입:
    dict: {'EPR': pd.Series} - 수익주가비율 값을 포함한 딕셔너리
    """
    epr_value = eps / stock_price
    
    return {
        'EPR': epr_value
    }