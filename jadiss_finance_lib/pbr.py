# PBR(Price to Book Ratio, 주가순자산비율)은 주가를 BPS로 나눈 값으로, 주식의 시장가치와 장부가치의 비율을 나타내는 재무지표입니다. 자산 가치 관점에서 기업을 평가합니다.
# PBR의 구성 요소:
# 주가(Stock Price):
# 현재 시장에서 거래되고 있는 주식의 가격입니다.
# BPS(Book Value Per Share):
# 주당순자산가치로, 주식 1주당 순자산 가치입니다.
# PBR의 특징:
# 자산 가치 비율:
# 시장가치가 장부가치의 몇 배인지를 보여줍니다.
# 성장성 반영:
# 높은 PBR은 미래 성장에 대한 시장의 기대를 반영합니다.
# 청산 가치 관점:
# PBR이 1 미만이면 시장가치가 청산가치보다 낮은 상태입니다.
# 업종별 차이:
# 업종에 따라 적정 PBR 수준이 크게 다릅니다.
# PBR 활용:
# 저평가 판단: 낮은 PBR은 주가가 순자산 대비 저평가 가능성
# 가치 투자: 자산 가치 기준 투자 판단에 활용
# 업종 비교: 동일 업종 내 기업들의 상대적 가치 평가
# 성장주 판별: 높은 PBR은 성장성이 높은 기업일 가능성
# 주의사항:
# 장부 가치 한계: 실제 자산 가치와 장부 가치의 차이
# 업종별 특성: 무형자산 비중이 높은 업종에서는 더 높은 PBR이 일반적
# 시장 상황: 시장 전체의 밸류에이션 수준 고려 필요

import pandas as pd

def pbr(bps, stock_price):
    """
    PBR(주가순자산비율) 계산
    
    입력 타입:
    bps (pd.Series): 주당순자산가치(BPS) 데이터 시리즈
    stock_price (pd.Series): 주가 데이터 시리즈
    
    출력 타입:
    dict: {'PBR': pd.Series} - 주가순자산비율 값을 포함한 딕셔너리
    """
    pbr_value = stock_price / bps
    
    return {
        'PBR': pbr_value
    }