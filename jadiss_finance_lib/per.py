# PER(Price to Earnings Ratio, 주가수익비율)은 주가를 EPS로 나눈 값으로, 주식의 시장가치와 수익성의 비율을 나타내는 재무지표입니다. 수익 대비 주가 수준을 평가합니다.
# PER의 구성 요소:
# 주가(Stock Price):
# 현재 시장에서 거래되고 있는 주식의 가격입니다.
# EPS(Earnings Per Share):
# 주당순이익으로, 기업이 주식 1주당 창출한 순이익입니다.
# PER의 특징:
# 수익성 평가:
# 주가가 순이익의 몇 배인지를 보여주는 지표입니다.
# 성장성 반영:
# 높은 PER은 미래 성장에 대한 시장의 기대를 반영합니다.
# 투자 회수 기간:
# 현재 수익 수준이 유지된다면 투자금을 회수하는 데 걸리는 이론적 기간입니다.
# 업종별 차이:
# 업종에 따라 적정 PER 수준이 크게 다릅니다.
# PER 활용:
# 저평가 판단: 낮은 PER은 주가가 수익 대비 저평가 가능성
# 성장주 판별: 높은 PER은 높은 성장성을 기대하는 기업일 가능성
# 업종 비교: 동일 업종 내 기업들의 상대적 가치 평가
# 시장 심리: 시장 전체 PER 추이로 투자 심리 파악
# 주의사항:
# 일시적 수익: 일회성 이익/손실이 포함된 경우 왜곡될 수 있음
# 적자 기업: 순이익이 마이너스인 경우 PER 계산이 불가능
# 성장성 차이: 동일 PER이라도 성장성에 따라 평가가 달라짐
# 업종별 특성: 업종에 따라 적정 PER 수준이 다름

import pandas as pd

def per(eps, stock_price):
    """
    PER(주가수익비율) 계산
    
    입력 타입:
    eps (pd.Series): 주당순이익(EPS) 데이터 시리즈
    stock_price (pd.Series): 주가 데이터 시리즈
    
    출력 타입:
    dict: {'PER': pd.Series} - 주가수익비율 값을 포함한 딕셔너리
    """
    per_value = stock_price / eps
    
    return {
        'PER': per_value
    }