# PSR(Price to Sales Ratio, 주가매출비율)은 주가를 SPS로 나눈 값으로, 주식의 시장가치와 매출의 비율을 나타내는 재무지표입니다. 매출 대비 주가 수준을 평가합니다.
# PSR의 구성 요소:
# 주가(Stock Price):
# 현재 시장에서 거래되고 있는 주식의 가격입니다.
# SPS(Sales Per Share):
# 주당매출액으로, 주식 1주당 매출액입니다.
# PSR의 특징:
# 매출 기준 평가:
# 주가가 매출의 몇 배인지를 보여주는 지표입니다.
# 수익성 이전 평가:
# 순이익이 없거나 적자인 기업도 평가 가능합니다.
# 업종별 차이:
# 업종에 따라 적정 PSR 수준이 크게 다릅니다.
# 안정성:
# 매출은 이익보다 변동성이 적어 더 안정적인 지표입니다.
# PSR 활용:
# 성장주 평가: 수익성이 낮지만 매출 성장이 높은 기업 평가
# 저평가 판단: 낮은 PSR은 매출 대비 저평가 가능성
# 업종 분석: 매출 중심 업종(유통, 서비스 등)에서 유용
# 턴어라운드: 적자 기업의 회복 가능성 평가
# 주의사항:
# 수익성 무관: 매출만 고려하므로 수익성은 별도 확인 필요
# 마진 차이: 동일 PSR이라도 이익률에 따라 가치가 다름
# 업종별 차이: 업종에 따라 적정 PSR 수준이 크게 다름
# 일회성 요인: 특별한 매출 증가 요인이 포함될 수 있음

import pandas as pd

def psr(sps, stock_price):
    """
    PSR(주가매출비율) 계산
    
    입력 타입:
    sps (pd.Series): 주당매출액(SPS) 데이터 시리즈
    stock_price (pd.Series): 주가 데이터 시리즈
    
    출력 타입:
    dict: {'PSR': pd.Series} - 주가매출비율 값을 포함한 딕셔너리
    """
    psr_value = stock_price / sps
    
    return {
        'PSR': psr_value
    }