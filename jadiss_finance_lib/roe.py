# ROE(Return on Equity, 자기자본이익률)는 기업이 자기자본을 얼마나 효율적으로 활용하여 이익을 창출했는지를 나타내는 핵심 재무지표입니다. 주주가 투자한 자본 대비 수익률을 측정합니다.
# ROE의 구성 요소:
# 순이익(Net Income):
# 기업이 일정 기간 동안 벌어들인 최종 이익으로, 모든 비용과 세금을 차감한 후의 이익입니다.
# 자기자본(Shareholders' Equity):
# 총자산에서 총부채를 차감한 값으로, 주주에게 귀속되는 순자산입니다.
# ROE의 특징:
# 자본 효율성:
# 주주가 투자한 자본을 얼마나 효율적으로 활용했는지를 보여줍니다.
# 수익성 지표:
# 기업의 전반적인 수익성과 경영 효율성을 나타냅니다.
# 투자 매력도:
# 높은 ROE는 투자자에게 매력적인 투자 대상임을 시사합니다.
# 성장 가능성:
# 높은 ROE는 내부 자금으로 성장할 수 있는 능력을 나타냅니다.
# ROE 분석 (듀폰 분석):
# ROE = 순이익률 × 자산회전율 × 자기자본승수
# 순이익률 = 순이익 ÷ 매출액 (수익성)
# 자산회전율 = 매출액 ÷ 총자산 (효율성)
# 자기자본승수 = 총자산 ÷ 자기자본 (레버리지)
# ROE 활용:
# 기업 비교: 동일 업종 내 기업들의 자본 효율성 비교
# 시계열 분석: 기업의 수익성 개선 또는 악화 추세 파악
# 투자 판단: 높은 ROE 기업에 대한 투자 우선순위 결정
# 배당 정책: ROE가 높을수록 배당 여력이 증가
# 주의사항:
# 레버리지 효과: 과도한 부채로 인한 ROE 상승은 위험할 수 있음
# 일회성 요인: 특별손익 등이 포함된 경우 지속가능성 검토 필요
# 업종별 차이: 업종에 따라 적정 ROE 수준이 다름
# 자본 구조: 자본 구조 변화가 ROE에 미치는 영향 고려

import pandas as pd

def roe(net_income, shareholders_equity):
    """
    ROE(자기자본이익률) 계산
    
    입력 타입:
    net_income (pd.Series): 순이익 데이터 시리즈
    shareholders_equity (pd.Series): 자기자본(순자산) 데이터 시리즈
    
    출력 타입:
    dict: {'ROE': pd.Series} - 자기자본이익률 값을 포함한 딕셔너리 (백분율)
    """
    roe_value = (net_income / shareholders_equity) * 100
    
    return {
        'ROE': roe_value
    }