# SPR(Sales Price Ratio, 매출주가비율)은 SPS를 주가로 나눈 값으로, PSR의 역수에 해당하는 재무지표입니다. 주가 대비 매출 비율을 나타내며, 매출 효율성 관점에서 기업을 평가합니다.
# SPR의 구성 요소:
# SPS(Sales Per Share):
# 주당매출액으로, 주식 1주당 매출액입니다.
# 주가(Stock Price):
# 현재 시장에서 거래되고 있는 주식의 가격입니다.
# SPR의 특징:
# 매출 효율성:
# 주가에 대한 매출의 비율을 직접적으로 보여줍니다.
# PSR의 역수:
# SPR = 1/PSR 관계로, PSR이 높으면 SPR은 낮아집니다.
# 성장성 평가:
# 매출 성장 기업의 가치 평가에 유용합니다.
# 업종 비교:
# 동일 업종 내 매출 효율성 비교가 가능합니다.
# SPR 활용:
# 성장주 평가: 수익성이 낮지만 매출 성장이 높은 기업 평가
# 저평가 판단: 높은 SPR은 매출 대비 저평가 가능성
# 업종 분석: 매출 중심 업종(유통, 서비스 등)에서 유용
# 턴어라운드: 적자 기업의 회복 가능성 평가
# 주의사항:
# 수익성 무관: 매출만 고려하므로 수익성은 별도 확인 필요
# 마진 변동: 매출 증가가 수익 증가로 이어지지 않을 수 있음
# 업종별 차이: 업종에 따라 적정 SPR 수준이 크게 다름
# 일회성 요인: 특별한 매출 증가 요인이 포함될 수 있음

import pandas as pd

def spr(sps, stock_price):
    """
    SPR(매출주가비율) 계산
    
    입력 타입:
    sps (pd.Series): 주당매출액(SPS) 데이터 시리즈
    stock_price (pd.Series): 주가 데이터 시리즈
    
    출력 타입:
    dict: {'SPR': pd.Series} - 매출주가비율 값을 포함한 딕셔너리
    """
    spr_value = sps / stock_price
    
    return {
        'SPR': spr_value
    }