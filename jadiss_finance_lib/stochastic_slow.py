# 스토캐스틱 슬로우(Stochastic Slow)는 기술적 분석에서 사용되는 지표인 스토캐스틱 지표의 한 종류로, 패스트 스토캐스틱의 변동성을 줄여 안정성을 높인 지표입니다. 알파스퀘어에 따르면 %K와 %D라는 두 가지 선으로 구성되며, %D는 %K의 이동 평균입니다. 스토캐스틱 슬로우는 과매수/과매도 구간을 판단하여 매매 시점을 결정하는 데 활용됩니다. 
# 스토캐스틱 슬로우의 구성 요소:
# %K:
# 스토캐스틱 패스트의 %D와 동일하며, 현재 가격이 특정 기간 최고가와 최저가 범위 내에서 어느 위치에 있는지를 나타냅니다.
# %D:
# %K의 이동 평균으로, %K보다 움직임이 둔하며 안정적인 신호를 제공합니다. 
# 스토캐스틱 슬로우의 특징:
# 안정성:
# 패스트 스토캐스틱에 비해 변동성이 적어 가짜 신호를 줄여줍니다.
# 둔감성:
# %D 선의 이동 평균으로 인해 %K보다 움직임이 둔하여 추세 변화를 파악하기에는 느릴 수 있습니다.
# 과매수/과매도:
# 0~100% 범위에서 움직이며, 80 이상은 과매수, 20 이하는 과매도로 간주합니다.
# 매매 신호:
# %K 선이 %D 선을 상향 돌파하면 매수 신호, 하향 돌파하면 매도 신호로 해석됩니다. 
# 스토캐스틱 슬로우 활용:
# 추세 판단:
# %K와 %D의 움직임을 통해 추세의 강도와 방향을 파악할 수 있습니다.
# 매매 시점 결정:
# 과매수/과매도 구간 진입 및 돌파 시점을 활용하여 매수/매도 시점을 결정합니다.
# 다른 지표와 함께 사용:
# 단독으로 사용하기보다는 다른 기술적 지표와 함께 사용하여 신뢰도를 높이는 것이 좋습니다. 
# 주의사항:
# 추세장에서는 둔감할 수 있음:
# 횡보장이나 박스권에서 유용한 반면, 추세가 강하게 형성된 구간에서는 정확도가 떨어질 수 있습니다.
# 다른 지표와 조합:
# 단독 사용보다는 다른 지표와 함께 사용하여 신뢰도를 높이는 것이 좋습니다. 알파스퀘어의 글에 따르면 

import pandas as pd

def stochastic_slow(high, low, close, k_period=14, d_period=3):
    """
    스토캐스틱 슬로우 지표 계산
    
    입력 타입:
    high (pd.Series): 고가 데이터 시리즈
    low (pd.Series): 저가 데이터 시리즈
    close (pd.Series): 종가 데이터 시리즈
    k_period (int): %K 계산 기간 (기본값: 14)
    d_period (int): %D 계산 기간 (기본값: 3)
    
    출력 타입:
    dict: {'%K': pd.Series, '%D': pd.Series} - 스토캐스틱 슬로우 지표들을 포함한 딕셔너리
    """
    # 최고가와 최저가 계산
    highest_high = high.rolling(window=k_period).max()
    lowest_low = low.rolling(window=k_period).min()
    
    # %K 계산 (Fast Stochastic의 %D와 동일)
    k_percent = ((close - lowest_low) / (highest_high - lowest_low)) * 100
    
    # %D 계산 (%K의 이동평균)
    d_percent = k_percent.rolling(window=d_period).mean()
    
    return {
        '%K': k_percent,
        '%D': d_percent
    }